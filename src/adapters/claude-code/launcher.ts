import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { steinwallHome } from "../../core/paths.js";
import { pluginRoot } from "./io.js";

/** ~/.steinwall/bin/steinwall.mjs: a stable CLI path for agents and skills, whatever the plugin's install path. */
export const cliLauncher = () => join(steinwallHome(), "bin", "steinwall.mjs");

const LAUNCHER = (root: string) => `// Generated by SteinWall. Runs the CLI of the installed plugin.
import { pathToFileURL } from "node:url";
await import(pathToFileURL(${JSON.stringify(join(root, "dist", "cli.js"))}).href);
`;

/** Write or refresh the launcher when it points somewhere else (new version, other install). */
export function installCliLauncher(root = pluginRoot()): void {
  const content = LAUNCHER(root);
  const path = cliLauncher();
  if (existsSync(path) && readFileSync(path, "utf8") === content) return;
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
}
